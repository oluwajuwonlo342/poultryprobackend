const Batch = require('../models/Batch');
const Expense = require('../models/Expense');
const DailyRecord = require('../models/DailyRecord');
const Sale = require('../models/Sale');
const WeightRecord = require('../models/WeightRecord');
const { calculateMeatFCR, calculateMortalityRate } = require('../utils/calculations');

exports.createBatch = async (req, res, next) => {
  try {
    const {
      batchName,
      batchCode,
      category,
      breed,
      initialQuantity,
      purchaseDate,
      arrivalDate,
      ageAtArrivalDays,
      initialAvgWeightKg,
      supplier,
      purchaseCost,
      housingLocation,
      notes,
    } = req.body;

    const batch = await Batch.create({
      farm: req.farmId,
      batchName,
      batchCode: batchCode || `BCH-${Date.now().toString().slice(-6)}`,
      category,
      breed,
      initialQuantity: Number(initialQuantity),
      currentQuantity: Number(initialQuantity),
      purchaseDate,
      arrivalDate: arrivalDate || purchaseDate,
      ageAtArrivalDays: Number(ageAtArrivalDays || 1),
      initialAvgWeightKg: Number(initialAvgWeightKg || 0.042),
      latestAvgWeightKg: Number(initialAvgWeightKg || 0.042),
      supplier,
      purchaseCost: Number(purchaseCost || 0),
      housingLocation,
      notes,
      populationHistory: [
        {
          date: arrivalDate || purchaseDate,
          type: 'initial',
          quantityChange: Number(initialQuantity),
          balanceAfter: Number(initialQuantity),
          reason: 'Initial batch stocking',
          recordedBy: req.user._id,
        },
      ],
    });

    // Automatically log bird purchase in Expense ledger (prevents double counting via autoGeneratedSource)
    if (Number(purchaseCost) > 0) {
      await Expense.create({
        farm: req.farmId,
        batch: batch._id,
        title: `Stock Purchase: ${batch.batchName} (${batch.initialQuantity} ${batch.category})`,
        category: 'Bird Purchases',
        amount: Number(purchaseCost),
        expenseDate: purchaseDate,
        description: `Supplier: ${supplier || 'N/A'}`,
        autoGeneratedSource: 'batch_purchase',
        sourceReferenceId: batch._id,
        recordedBy: req.user._id,
      });
    }

    res.status(201).json(batch);
  } catch (error) {
    next(error);
  }
};

exports.getBatchesWithMetrics = async (req, res, next) => {
  try {
    const { status } = req.query;
    const filter = { farm: req.farmId };
    if (status) filter.status = status;

    const batches = await Batch.find(filter).sort({ createdAt: -1 });

    // Enrich each batch with live FCR, feed consumed, revenue, expenses, and net profit
    const enriched = await Promise.all(
      batches.map(async (batch) => {
        const [feedAgg, expenseAgg, salesAgg] = await Promise.all([
          DailyRecord.aggregate([
            { $match: { farm: batch.farm, batch: batch._id, recordType: 'feeding' } },
            { $group: { _id: null, totalFeedKg: { $sum: '$feedQuantityKg' } } },
          ]),
          Expense.aggregate([
            { $match: { farm: batch.farm, batch: batch._id } },
            { $group: { _id: null, totalExpenses: { $sum: '$amount' } } },
          ]),
          Sale.aggregate([
            { $match: { farm: batch.farm, batch: batch._id } },
            { $group: { _id: null, totalRevenue: { $sum: '$totalAmount' } } },
          ]),
        ]);

        const totalFeedConsumedKg = feedAgg[0]?.totalFeedKg || 0;
        const totalExpenses = expenseAgg[0]?.totalExpenses || 0;
        const totalRevenue = salesAgg[0]?.totalRevenue || 0;

        const fcr = calculateMeatFCR({
          totalFeedConsumedKg,
          currentPopulation: batch.currentQuantity,
          initialAvgWeightKg: batch.initialAvgWeightKg,
          latestAvgWeightKg: batch.latestAvgWeightKg,
          category: batch.category,
        });

        const mortalityRate = calculateMortalityRate({
          birdsLost: batch.totalMortality,
          startingPopulation: batch.initialQuantity,
        });

        return {
          ...batch.toObject(),
          metrics: {
            totalFeedConsumedKg,
            fcr,
            mortalityRate,
            totalExpenses,
            totalRevenue,
            netProfit: totalRevenue - totalExpenses,
          },
        };
      })
    );

    res.json(enriched);
  } catch (error) {
    next(error);
  }
};

exports.recordWeightSample = async (req, res, next) => {
  try {
    const { batchId } = req.params;
    const { measurementDate, birdsSampled, averageWeightKg, notes } = req.body;

    const batch = await Batch.findOne({ _id: batchId, farm: req.farmId });
    if (!batch) return res.status(404).json({ message: 'Batch not found.' });

    batch.latestAvgWeightKg = Number(averageWeightKg);
    await batch.save();

    const feedAgg = await DailyRecord.aggregate([
      { $match: { farm: req.farmId, batch: batch._id, recordType: 'feeding' } },
      { $group: { _id: null, totalFeedKg: { $sum: '$feedQuantityKg' } } },
    ]);

    const calculatedFCR = calculateMeatFCR({
      totalFeedConsumedKg: feedAgg[0]?.totalFeedKg || 0,
      currentPopulation: batch.currentQuantity,
      initialAvgWeightKg: batch.initialAvgWeightKg,
      latestAvgWeightKg: Number(averageWeightKg),
      category: batch.category,
    });

    const record = await WeightRecord.create({
      farm: req.farmId,
      batch: batch._id,
      measurementDate: measurementDate || new Date(),
      birdsSampled: Number(birdsSampled),
      averageWeightKg: Number(averageWeightKg),
      calculatedFCR,
      notes,
      recordedBy: req.user._id,
    });

    res.status(201).json({ record, updatedBatch: batch });
  } catch (error) {
    next(error);
  }
};