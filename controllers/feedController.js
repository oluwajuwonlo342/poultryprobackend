const FeedProduct = require('../models/FeedProduct');
const FeedTransaction = require('../models/FeedTransaction');
const Expense = require('../models/Expense');

exports.createFeedProduct = async (req, res, next) => {
  try {
    const {
      productName,
      feedType,
      manufacturer,
      unit,
      initialStockKg,
      lowStockThresholdKg,
      purchasePriceTotal,
      supplier,
      expiryDate,
    } = req.body;

    const stockKg = Number(initialStockKg || 0);
    const totalCost = Number(purchasePriceTotal || 0);
    const avgCostPerKg = stockKg > 0 && totalCost > 0 ? Number((totalCost / stockKg).toFixed(2)) : 0;

    const product = await FeedProduct.create({
      farm: req.farmId,
      productName,
      feedType,
      manufacturer,
      unit: unit || 'kg',
      currentStockKg: stockKg,
      lowStockThresholdKg: Number(lowStockThresholdKg || 100),
      weightedAvgCostPerKg: avgCostPerKg,
      supplier,
      expiryDate,
    });

    if (stockKg > 0) {
      const tx = await FeedTransaction.create({
        farm: req.farmId,
        feedProduct: product._id,
        transactionType: 'purchase',
        quantityKg: stockKg,
        unitCostPerKg: avgCostPerKg,
        totalCost,
        supplier,
        notes: 'Opening feed inventory stock',
        recordedBy: req.user._id,
      });

      if (totalCost > 0) {
        await Expense.create({
          farm: req.farmId,
          title: `Feed Purchase: ${product.productName} (${stockKg} kg)`,
          category: 'Feed Purchases',
          amount: totalCost,
          description: `Supplier: ${supplier || 'N/A'}`,
          autoGeneratedSource: 'feed_purchase',
          sourceReferenceId: tx._id,
          recordedBy: req.user._id,
        });
      }
    }

    res.status(201).json(product);
  } catch (error) {
    next(error);
  }
};

exports.recordFeedPurchase = async (req, res, next) => {
  try {
    const { feedProductId, quantityKg, totalCost, supplier, purchaseDate, notes } = req.body;
    const product = await FeedProduct.findOne({ _id: feedProductId, farm: req.farmId });
    if (!product) return res.status(404).json({ message: 'Feed product not found.' });

    const addedKg = Number(quantityKg);
    const cost = Number(totalCost);
    const currentVal = product.currentStockKg * product.weightedAvgCostPerKg;
    const newTotalKg = product.currentStockKg + addedKg;

    product.weightedAvgCostPerKg =
      newTotalKg > 0 ? Number(((currentVal + cost) / newTotalKg).toFixed(2)) : product.weightedAvgCostPerKg;
    product.currentStockKg = newTotalKg;
    if (supplier) product.supplier = supplier;
    await product.save();

    const tx = await FeedTransaction.create({
      farm: req.farmId,
      feedProduct: product._id,
      transactionType: 'purchase',
      quantityKg: addedKg,
      unitCostPerKg: addedKg > 0 ? Number((cost / addedKg).toFixed(2)) : 0,
      totalCost: cost,
      supplier,
      transactionDate: purchaseDate || new Date(),
      notes,
      recordedBy: req.user._id,
    });

    if (cost > 0) {
      await Expense.create({
        farm: req.farmId,
        title: `Feed Restock: ${product.productName} (${addedKg} kg)`,
        category: 'Feed Purchases',
        amount: cost,
        expenseDate: purchaseDate || new Date(),
        description: `Supplier: ${supplier || 'N/A'}`,
        autoGeneratedSource: 'feed_purchase',
        sourceReferenceId: tx._id,
        recordedBy: req.user._id,
      });
    }

    res.status(201).json({ product, transaction: tx });
  } catch (error) {
    next(error);
  }
};

exports.recordStockAdjustment = async (req, res, next) => {
  try {
    const { feedProductId, adjustmentKg, reason } = req.body;
    const product = await FeedProduct.findOne({ _id: feedProductId, farm: req.farmId });
    if (!product) return res.status(404).json({ message: 'Feed product not found.' });

    const delta = Number(adjustmentKg);
    if (product.currentStockKg + delta < 0) {
      return res.status(400).json({ message: 'Stock adjustment cannot result in negative inventory.' });
    }

    product.currentStockKg += delta;
    await product.save();

    const tx = await FeedTransaction.create({
      farm: req.farmId,
      feedProduct: product._id,
      transactionType: 'adjustment',
      quantityKg: delta,
      notes: reason || 'Authorized stock audit adjustment',
      recordedBy: req.user._id,
    });

    res.json({ product, transaction: tx });
  } catch (error) {
    next(error);
  }
};