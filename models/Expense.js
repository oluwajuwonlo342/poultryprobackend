// server/models/Expense.js
const mongoose = require('mongoose');

const expenseSchema = new mongoose.Schema(
  {
    farm: { type: mongoose.Schema.Types.ObjectId, ref: 'Farm', required: true, index: true },
    batch: { type: mongoose.Schema.Types.ObjectId, ref: 'Batch' }, // Optional for farm-wide overhead
    title: { type: String, required: true, trim: true },
    category: {
      type: String,
      enum: [
        'Bird Purchases',
        'Feed Purchases',
        'Vaccines',
        'Medication',
        'Labour',
        'Electricity',
        'Water',
        'Transportation',
        'Equipment',
        'Repairs',
        'Other',
      ],
      required: true,
    },
    amount: { type: Number, required: true, min: 0 },
    expenseDate: { type: Date, default: Date.now, index: true },
    paymentMethod: {
      type: String,
      enum: ['Cash', 'Bank Transfer', 'POS', 'Card'],
      default: 'Bank Transfer',
    },
    description: { type: String, trim: true },
    receiptUrl: { type: String, default: '' },
    autoGeneratedSource: {
      type: String,
      enum: ['manual', 'batch_purchase', 'feed_purchase'],
      default: 'manual',
    },
    sourceReferenceId: { type: mongoose.Schema.Types.ObjectId },
    recordedBy: { type: mongoose.Schema.Types.ObjectId, ref: 'User', required: true },
  },
  { timestamps: true }
);

module.exports = mongoose.model('Expense', expenseSchema);